def generate_complaint_pdf(complaint_text: str, title: str = "Legal Complaint Draft") -> bytes:
    """
    Compiles complaint text into an elegant, professional A4 PDF using ReportLab.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    # Custom styles
    header_style = ParagraphStyle(
        "DocHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=15,
        leading=19,
        textColor=colors.HexColor("#0F2942"),
        alignment=1,  # Center
        spaceAfter=8
    )

    tagline_style = ParagraphStyle(
        "DocTagline",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#8C7030"),
        alignment=1,
        spaceAfter=12
    )

    body_style = ParagraphStyle(
        "DocBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9.5,
        leading=14,
        textColor=colors.HexColor("#212529"),
        spaceAfter=6
    )

    bold_body_style = ParagraphStyle(
        "DocBoldBody",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#0F2942"),
        spaceAfter=6
    )

    disclaimer_style = ParagraphStyle(
        "DocDisclaimer",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#6c757d"),
        spaceBefore=10,
        spaceAfter=10
    )

    story = []

    # App Header branding
    story.append(Paragraph("NYAYASATHI LEGAL DRAFTING ASSISTANT", header_style))
    story.append(Paragraph("Know Your Rights. Take Your Next Step. | FirstCommit '26 Hackathon Edition", tagline_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#D4AF37"), spaceAfter=14))

    # Split lines and build paragraphs
    lines = complaint_text.split("\n")
    for line in lines:
        stripped = line.strip()
        if not stripped:
            story.append(Spacer(1, 4))
            continue

        if stripped.startswith("DISCLAIMER:") or "not constitute an attorney-client relationship" in stripped:
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#CCCCCC"), spaceBefore=6, spaceAfter=6))
            story.append(Paragraph(stripped, disclaimer_style))
        elif stripped.startswith("SUBJECT:") or stripped.startswith("FORMAL ") or stripped.endswith(":") and len(stripped) < 60:
            story.append(Paragraph(stripped.replace("&", "&amp;"), bold_body_style))
        else:
            story.append(Paragraph(stripped.replace("&", "&amp;"), body_style))

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()
